#!/usr/bin/env node
/**
 * Generates the mirrored per-strategy API (Android: one module per strategy with the
 * same suffix rules), the pure-CSS fallback stylesheets and the SCSS functions.
 *
 *   node scripts/generate.mjs           # write files
 *   node scripts/generate.mjs --check   # fail if committed files are stale
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

/** id, display name, exported constant, import path, name prefix, pure-CSS factor per axis length. */
export const STRATEGIES = [
  { id: 'scaled', name: 'Scaled', constant: 'SCALED', from: '../core/scaled', prefix: '', css: (d) => `calc(${d} / 300)`, exactCss: true },
  { id: 'percent', name: 'Percent', constant: 'PERCENT', from: '../strategies/percent', prefix: 'p', css: (d) => `calc(${d} / 300)`, exactCss: true },
  { id: 'power', name: 'Power', constant: 'POWER', from: '../strategies/power', prefix: 'pw', css: (d) => `calc(${d} / 300)`, exactCss: false },
  {
    id: 'fluid', name: 'Fluid', constant: 'FLUID', from: '../strategies/fluid', prefix: 'f', exactCss: true,
    css: (d) => `clamp(0.8px, 0.8px + (${d} - 320px) * ${(0.4 / 448).toFixed(9)}, 1.2px)`,
  },
  {
    id: 'auto', name: 'Auto', constant: 'AUTO', from: '../strategies/auto', prefix: 'a', exactCss: false,
    css: (d) => `min(${d} / 300, 1.6px + (${d} - 480px) * ${(0.4 / 300).toFixed(9)})`,
  },
  {
    id: 'diagonal', name: 'Diagonal', constant: 'DIAGONAL', from: '../strategies/diagonal', prefix: 'dg', exactCss: true,
    css: () => `calc(hypot(100vw, 100vh) / 611.6305)`, supports: 'width: hypot(1px, 1px)',
  },
  {
    id: 'fill', name: 'Fill', constant: 'FILL', from: '../strategies/fill', prefix: 'fl', exactCss: true,
    css: () => `max(min(100vw, 100vh) / 300, max(100vw, 100vh) / 533)`,
  },
  {
    id: 'fit', name: 'Fit', constant: 'FIT', from: '../strategies/fit', prefix: 'ft', exactCss: true,
    css: () => `min(min(100vw, 100vh) / 300, max(100vw, 100vh) / 533)`,
  },
  {
    id: 'interpolated', name: 'Interpolated', constant: 'INTERPOLATED', from: '../strategies/interpolated', prefix: 'i', exactCss: true,
    css: (d) => `calc(0.5px + ${d} / 600)`,
  },
  { id: 'logarithmic', name: 'Logarithmic', constant: 'LOGARITHMIC', from: '../strategies/logarithmic', prefix: 'log', css: () => `1px`, exactCss: false },
  {
    id: 'perimeter', name: 'Perimeter', constant: 'PERIMETER', from: '../strategies/perimeter', prefix: 'pr', exactCss: true,
    css: () => `calc((100vw + 100vh) / 833)`,
  },
  { id: 'density', name: 'Density', constant: 'DENSITY', from: '../strategies/density', prefix: 'd', css: () => `1px`, exactCss: false, density: true },
];

// Must match VARIANTS in src/core/strategy.ts (slot = variant * 4 + flags).
const VARIANTS = [
  { axis: 's', token: '', label: 'smallest width' },
  { axis: 'h', token: '', label: 'height' },
  { axis: 'w', token: '', label: 'width' },
  { axis: 's', token: 'Ph', label: 'smallest width → height in portrait', inverter: 'SW_TO_PH', orient: 'portrait', to: 'h' },
  { axis: 's', token: 'Lh', label: 'smallest width → height in landscape', inverter: 'SW_TO_LH', orient: 'landscape', to: 'h' },
  { axis: 's', token: 'Pw', label: 'smallest width → width in portrait', inverter: 'SW_TO_PW', orient: 'portrait', to: 'w' },
  { axis: 's', token: 'Lw', label: 'smallest width → width in landscape', inverter: 'SW_TO_LW', orient: 'landscape', to: 'w' },
  { axis: 'h', token: 'Lw', label: 'height → width in landscape', inverter: 'PH_TO_LW', orient: 'landscape', to: 'w' },
  { axis: 'h', token: 'Pw', label: 'height → width in portrait', inverter: 'LH_TO_PW', orient: 'portrait', to: 'w' },
  { axis: 'w', token: 'Lh', label: 'width → height in landscape', inverter: 'PW_TO_LH', orient: 'landscape', to: 'h' },
  { axis: 'w', token: 'Ph', label: 'width → height in portrait', inverter: 'LW_TO_PH', orient: 'portrait', to: 'h' },
];
const FLAGS = [
  { suffix: '', label: '' },
  { suffix: 'a', label: ' · aspect ratio' },
  { suffix: 'i', label: ' · ignore multi-window' },
  { suffix: 'ia', label: ' · aspect ratio · ignore multi-window' },
];
const AXIS_QUALIFIER = { s: 'DpQualifier.SMALL_WIDTH', h: 'DpQualifier.HEIGHT', w: 'DpQualifier.WIDTH' };
const AXIS_LEN = { s: 'min(100vw, 100vh)', h: '100vh', w: '100vw' };
const KINDS = [
  { kind: 'dp', label: 'layout' },
  { kind: 'sp', label: 'text (× font scale)' },
  { kind: 'em', label: 'text (no font scale)' },
];

const HEADER = '// AUTO-GENERATED by scripts/generate.mjs — do not edit by hand.\n';

/** Every accessor name a strategy exposes, with its slot / kind / px flag. */
export function accessorNames(prefix) {
  const out = [];
  VARIANTS.forEach((v, vi) => {
    FLAGS.forEach((f, fi) => {
      for (const { kind } of KINDS) {
        const name = `${prefix}${v.axis}${kind}${v.token}${f.suffix}`;
        out.push({ name, slot: vi * 4 + fi, kind, px: false, variant: v, flag: f });
        out.push({ name: `${name}Px`, slot: vi * 4 + fi, kind, px: true, variant: v, flag: f });
      }
    });
  });
  return out;
}

/** CSS tokens published by the runtime (must match `strategyDeclarations` in runtime.ts). */
export function cssTokens(prefix) {
  const out = [];
  VARIANTS.forEach((v) => {
    FLAGS.forEach((f) => {
      out.push({ token: `${prefix}${v.axis}dp${v.token}${f.suffix}`, variant: v, kind: 'dp' });
      if (v.token === '') {
        out.push({ token: `${prefix}${v.axis}sp${f.suffix}`, variant: v, kind: 'sp' });
        out.push({ token: `${prefix}${v.axis}em${f.suffix}`, variant: v, kind: 'em' });
      }
    });
  });
  return out;
}

function genModule(s) {
  const P = s.prefix;
  const lines = [HEADER];
  lines.push(`import {`);
  lines.push(`  boundOf, dpFn, KIND_DP, KIND_SP, modeFn, pxFn, qualifierFn, rotateFn, screenFn, spFn, spPxFn, toDynamic,`);
  lines.push(`} from '../core/api';`);
  lines.push(`import { DimenBuilder } from '../core/builder';`);
  lines.push(`import { DpQualifier } from '../core/enums';`);
  lines.push(`import { register } from '../core/runtime';`);
  lines.push(`import { ${s.constant} } from '${s.from}';`);
  lines.push('');
  lines.push(`export { ${s.constant} };`);
  lines.push('');
  lines.push(`const T = /* @__PURE__ */ register(${s.constant});`);
  lines.push(`const B = /* @__PURE__ */ boundOf(${s.constant}, T);`);
  lines.push('');
  lines.push(`// ── Accessors: value (dp) → CSS px; \`Px\` → device px. ─────────────────────────`);
  const fn = { dp: ['dpFn', 'pxFn'], sp: ['spFn', 'spPxFn'], em: ['dpFn', 'pxFn'] };
  for (const a of accessorNames(P)) {
    const kindLabel = KINDS.find((k) => k.kind === a.kind).label;
    const unit = a.px ? 'device px' : 'CSS px';
    lines.push(`/** ${s.name} · ${a.variant.label}${a.flag.label} · ${kindLabel} → ${unit}. */`);
    lines.push(`export const ${a.name} = /* @__PURE__ */ ${fn[a.kind][a.px ? 1 : 0]}(T, ${a.slot});`);
  }
  lines.push('');
  lines.push(`// ── Generic resolvers (Android \`toDynamic${s.name}Dp\` / \`Px\` / \`Sp\` / \`SpPx\`). ──────`);
  lines.push(`/** Any qualifier / inverter / flag / custom k → CSS px. */`);
  lines.push(`export const toDynamic${s.name}Dp = /* @__PURE__ */ toDynamic(B, KIND_DP, false);`);
  lines.push(`/** Any qualifier / inverter / flag / custom k → device px. */`);
  lines.push(`export const toDynamic${s.name}Px = /* @__PURE__ */ toDynamic(B, KIND_DP, true);`);
  lines.push(`/** Text: any qualifier / options (\`fontScale\` default true) → CSS px. */`);
  lines.push(`export const toDynamic${s.name}Sp = /* @__PURE__ */ toDynamic(B, KIND_SP, false);`);
  lines.push(`/** Text → device px. */`);
  lines.push(`export const toDynamic${s.name}SpPx = /* @__PURE__ */ toDynamic(B, KIND_SP, true);`);
  lines.push('');
  lines.push(`// ── Facilitators: Rotate / Mode / Qualifier / Screen (+ Px, sp). ─────────────────`);
  const FAC = [
    ['Rotate', 'rotateFn', 'alternate value in the given orientation'],
    ['Mode', 'modeFn', 'alternate value for a UI mode'],
    ['Qualifier', 'qualifierFn', 'alternate value above a dp threshold'],
    ['Screen', 'screenFn', 'alternate value for UI mode + dp threshold'],
  ];
  for (const axis of ['s', 'h', 'w']) {
    for (const kind of ['dp', 'sp']) {
      for (const [fac, factory, label] of FAC) {
        for (const px of [false, true]) {
          const name = `${P}${axis}${kind}${fac}${px ? 'Px' : ''}`;
          lines.push(`/** ${s.name} · ${label} · ${kind === 'dp' ? 'layout' : 'text'} → ${px ? 'device' : 'CSS'} px. */`);
          lines.push(
            `export const ${name} = /* @__PURE__ */ ${factory}(B, ${AXIS_QUALIFIER[axis]}, ${kind === 'dp' ? 'KIND_DP' : 'KIND_SP'}, ${px});`,
          );
        }
      }
    }
  }
  lines.push('');
  lines.push(`// ── Builder (Android \`Dimen${s.name}\` / \`${s.name}Sp\`). ───────────────────────────`);
  const cls = `Dimen${s.name}`;
  lines.push(`/** Custom-dimension builder for the ${s.name.toLowerCase()} strategy. */`);
  lines.push(`export class ${cls} extends DimenBuilder {`);
  if (P) {
    for (const axis of ['s', 'h', 'w']) {
      for (const k of ['dp', 'sp', 'em']) {
        lines.push(`  get ${P}${axis}${k}(): number { return this.${axis}${k}; }`);
        lines.push(`  get ${P}${axis}${k}Px(): number { return this.${axis}${k}Px; }`);
      }
    }
  }
  lines.push(`}`);
  lines.push(`/** Starts a builder: \`${s.id}Dp(16).screen(UiModeType.TELEVISION, 40).${P}sdp\`. */`);
  lines.push(`export const ${s.id}Dp = (value: number): ${cls} => new ${cls}(B, value);`);
  lines.push(`/** Text builder (same class; read \`.${P}ssp\` / \`.${P}sem\`). */`);
  lines.push(`export const ${s.id}Sp = (value: number): ${cls} => new ${cls}(B, value);`);
  lines.push('');
  return lines.join('\n');
}

function decl(name, value) {
  return `  --${name}: ${value};`;
}

function genCss(s) {
  const lines = [`/* AUTO-GENERATED by scripts/generate.mjs — webdimens ${s.id} fallback tokens. */`];
  lines.push(
    s.exactCss
      ? `/* Pure-CSS ${s.id} tokens: exact (without the aspect-ratio "a" correction) until the JS runtime takes over. */`
      : `/* Approximate pure-CSS ${s.id} tokens; the JS runtime (install()) publishes the exact values. */`,
  );
  const tokens = cssTokens(s.prefix);
  const base = (v, axis) => (s.density ? '1px' : s.css(AXIS_LEN[axis]));
  const wrapOpen = s.supports ? `@supports (${s.supports}) {\n` : '';
  const wrapClose = s.supports ? `}\n` : '';
  let out = lines.join('\n') + '\n' + wrapOpen + ':root {\n';
  out += tokens.map((t) => decl(t.token, base(t.variant, t.variant.axis))).join('\n') + '\n}\n';
  for (const orient of ['portrait', 'landscape']) {
    const swapped = tokens.filter((t) => t.variant.orient === orient);
    if (!swapped.length || s.css('X') === s.css('Y')) continue;
    out += `@media (orientation: ${orient}) {\n  :root {\n`;
    out += swapped.map((t) => '  ' + decl(t.token, base(t.variant, t.variant.to))).join('\n') + '\n  }\n}\n';
  }
  if (s.density) {
    for (const r of [1.25, 1.5, 2, 2.5, 3, 4]) {
      out += `@media (min-resolution: ${r}dppx) {\n  :root {\n`;
      out += tokens.map((t) => '  ' + decl(t.token, `${r}px`)).join('\n') + '\n  }\n}\n';
    }
  }
  return out + wrapClose;
}

function genScss() {
  const lines = [
    `// AUTO-GENERATED by scripts/generate.mjs — do not edit by hand.`,
    `// Sass functions mirroring the Android extensions: \`padding: sdp(16)\` → \`calc(16 * var(--sdp))\`.`,
    `// Requires the CSS custom properties (JS runtime \`install()\` and/or webdimens CSS fallbacks).`,
    ``,
    `/// Generic form: dimen(sdp, 16) → calc(16 * var(--sdp)).`,
    `@function dimen($token, $value) {`,
    `  @return calc(#{$value} * var(--#{$token}));`,
    `}`,
    ``,
  ];
  for (const s of STRATEGIES) {
    lines.push(`// ── ${s.name} ──`);
    for (const t of cssTokens(s.prefix)) {
      lines.push(`@function ${t.token}($value) { @return calc(#{$value} * var(--${t.token})); }`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

function genGlobalTokens() {
  return (
    HEADER +
    `/** Per-strategy accessor names, used to assert API completeness in tests. */\n` +
    `export const ACCESSOR_COUNT_PER_STRATEGY = ${accessorNames('').length};\n`
  );
}

// ── Uniqueness check across all strategies (the global bundle flattens every name). ──
const seen = new Map();
for (const s of STRATEGIES) {
  const names = [
    ...accessorNames(s.prefix).map((a) => a.name),
    `toDynamic${s.name}Dp`, `toDynamic${s.name}Px`, `toDynamic${s.name}Sp`, `toDynamic${s.name}SpPx`,
    `${s.id}Dp`, `${s.id}Sp`, `Dimen${s.name}`,
  ];
  for (const axis of ['s', 'h', 'w'])
    for (const kind of ['dp', 'sp'])
      for (const fac of ['Rotate', 'Mode', 'Qualifier', 'Screen'])
        for (const px of ['', 'Px']) names.push(`${s.prefix}${axis}${kind}${fac}${px}`);
  for (const n of names) {
    if (seen.has(n)) throw new Error(`Name collision: ${n} (${seen.get(n)} vs ${s.id})`);
    seen.set(n, s.id);
  }
}

const files = new Map();
for (const s of STRATEGIES) {
  files.set(`src/generated/${s.id}.ts`, genModule(s));
  files.set(`css/strategies/${s.id}.css`, genCss(s));
}
files.set('src/generated/meta.ts', genGlobalTokens());
files.set('scss/_webdimens.scss', genScss());
files.set('css/webdimens.css', `/* webdimens — scaled tokens (default). Other strategies: css/strategies/<id>.css or css/all.css. */\n` + genCss(STRATEGIES[0]));
files.set(
  'css/all.css',
  `/* AUTO-GENERATED — every strategy's fallback tokens in one file. */\n` +
    STRATEGIES.map((s) => genCss(s)).join('\n'),
);

let stale = [];
for (const [rel, content] of files) {
  const path = join(root, rel);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) stale.push(rel);
    continue;
  }
  mkdirSync(dirname(path), { recursive: true });
  if (!existsSync(path) || readFileSync(path, 'utf8') !== content) writeFileSync(path, content);
}
if (check && stale.length) {
  console.error(`Generated files are stale — run \`npm run generate\`:\n  ${stale.join('\n  ')}`);
  process.exit(1);
}
console.log(check ? 'Generated files are up to date.' : `Generated ${files.size} files (${seen.size} unique API names).`);
